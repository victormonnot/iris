"""One bounded planning → local geometry → review pipeline per benchmark image."""

import time

from iris.benchmark import (
    PROTOCOL,
    SCORING,
    BenchmarkConflict,
    _digest,
    load_benchmark_manifest,
    open_benchmark_image,
    score_benchmark_outputs,
)
from iris.benchmark_multimodal import _microusd
from iris.benchmark_multimodal import attach_preview as external_preview

EXTERNAL_PROTOCOL = "iris-combined-trial-v1"
MODEL = "gpt-6-astra+sam3"
COMBINED_SCORING = {
    **SCORING,
    "scope": "Astra-reviewed native SAM boxes; SAM threshold precedes review, "
    "final confidence unavailable, no mask metrics or AP",
}


def provider_status(root, config=None, *, force=False):
    from iris.multimodal_provider import provider_status as openai_status
    from iris.sam_provider import provider_status as sam_status

    remote = openai_status(config["openai_config"] if config else None)
    local = sam_status(root, config["sam_config"] if config else None, force=force)
    missing = [status for status in (remote, local) if status["status"] != "ready"]
    return {
        "model": MODEL,
        "model_id": MODEL,
        "name": "Astra + SAM 3 · bounded plan and review",
        "external": True,
        "ready": not missing,
        "status": missing[0]["status"] if missing else "ready",
        "reason": " ".join(status["reason"] for status in missing) if missing else None,
        "multimodal": remote,
        "segmentation": local,
    }


def provider_catalog(store):
    return {
        "combined": provider_status(store.root),
        "combined_settings": {
            "max_external_calls_per_image": 2,
            "max_iterations": 1,
            "stages": ["planning", "grounding", "review"],
        },
    }


def work_plan(config, image_count):
    return {
        "image_count": image_count,
        "request_count": image_count * 2,
        "image_encodings": image_count,
        "prompt_evaluations": image_count * len(config["provider_config"]["taxonomy"]["classes"]),
        "max_iterations": 1,
        "warmup_passes": 0,
    }


def preview_config(store, benchmark_id, *, model_id, combined=None):
    from iris.combined_provider import freeze_config

    benchmark = store.get("benchmarks", benchmark_id)
    if benchmark is None:
        raise KeyError(benchmark_id)
    if benchmark["status"] != "tuning":
        raise BenchmarkConflict("This benchmark's configurations are already locked")
    options = {} if combined is None else combined
    if (
        model_id != MODEL
        or not isinstance(options, dict)
        or set(options) - {"multimodal", "segmentation"}
    ):
        raise ValueError("Choose the bounded Astra + SAM 3 combined profile")
    remote, local = options.get("multimodal", {}), options.get("segmentation", {})
    if (
        not isinstance(remote, dict)
        or not isinstance(local, dict)
        or set(remote) - {"image_long_edge", "reasoning_effort", "max_output_tokens"}
        or set(local) - {"threshold", "device"}
    ):
        raise ValueError("Unsupported combined settings; class phrases are generated by Astra")
    manifest = load_benchmark_manifest(store, benchmark_id)
    provider = freeze_config(
        manifest["taxonomy"],
        **remote,
        sam_threshold=local.get("threshold", 0.5),
        device=local.get("device", "cuda"),
    )
    config = {
        "protocol": PROTOCOL,
        "approach": "combined",
        "model_id": MODEL,
        "model_name": "GPT-6 Astra + SAM 3 · plan, ground, review",
        "provider_config": provider,
        "scoring": COMBINED_SCORING,
        "reference_manifest_sha256": benchmark["manifest_sha256"],
    }
    return {
        "benchmark_id": benchmark_id,
        "config": config,
        "fingerprint": _digest(config),
        "work": {
            role: work_plan(config, sum(frame["role"] == role for frame in manifest["frames"]))
            for role in ("tuning", "evaluation")
        },
        "provider_status": provider_status(store.root, provider),
        "warnings": [
            "Preparation is local. No image is sent and no model is loaded by saving this profile.",
            "One pass: Astra chooses one SAM phrase per class; SAM provides native boxes; "
            "Astra accepts, rejects or reclassifies those boxes. "
            "No additional search or new geometry.",
            "At most two external calls per image. The review request contains generated SAM "
            "proposals; its exact contents only exist after the first two stages.",
            "The combination is an experimental candidate, not evidence of improved quality. "
            "Reference annotations and human corrections never enter any stage.",
        ],
    }


def validate_config(config, manifest):
    from iris.combined_provider import validate_frozen_config

    provider = config.get("provider_config")
    validate_frozen_config(provider)
    if (
        config.get("model_id") != MODEL
        or provider["taxonomy"] != manifest["taxonomy"]
        or config.get("scoring") != COMBINED_SCORING
    ):
        raise ValueError("Frozen combined classes, models or scoring protocol changed")
    return config


def prepare_plan(store, config, frames):
    from iris.combined_provider import prepare_plan_request, review_template, safe_request
    from iris.sam_runtime import prepare_image

    settings = config["config"]["provider_config"]
    requests, total = [], 0
    for frame in frames:
        with open_benchmark_image(store, frame) as image:
            prepare_image(image)
            planning = prepare_plan_request(image, settings)
            review = review_template(image, settings)
        total += _microusd(planning["estimate"]["upper_bound_usd"])
        total += _microusd(review["estimate"]["upper_bound_usd"])
        requests.append(
            {
                "frame_id": frame["frame_id"],
                "planning": {"input": safe_request(planning), "estimate": planning["estimate"]},
                "review": {
                    "template": {k: v for k, v in review.items() if k != "image_bytes"},
                    "estimate": review["estimate"],
                },
                "image_url": (
                    f"/api/benchmark-configs/{config['id']}/frames/{frame['frame_id']}/input-image"
                ),
            }
        )
    status = provider_status(store.root, settings, force=True)
    return {
        "protocol": EXTERNAL_PROTOCOL,
        "provider": "openai",
        "model": settings["openai_config"]["model"],
        "runtime_identity": status["segmentation"].get("runtime", {}).get("identity"),
        "requests": requests,
        "estimate": {
            "currency": "USD",
            "upper_bound_usd": total / 1_000_000,
            "estimated_ceiling_microusd": total,
            "estimate_label": "Planning estimate for two bounded external stages per image",
            "basis": "Sum of per-stage allowances rounded up to micro-USD, including the "
            "maximum dynamic review input. Not a guaranteed provider billing cap or invoice.",
        },
        "provider_status": status,
    }


def attach_preview(store, preview, config, frames):
    return external_preview(preview, prepare_plan(store, config, frames))


def input_image(store, config_id, frame_id):
    from iris.benchmark import benchmark_frame, validate_benchmark_config
    from iris.combined_provider import prepare_plan_request

    config = store.get("benchmark_configs", config_id)
    if config is None or config["approach"] != "combined":
        raise KeyError(config_id)
    benchmark = store.get("benchmarks", config["benchmark_id"])
    manifest = load_benchmark_manifest(store, benchmark["id"])
    validate_benchmark_config(config, benchmark, manifest)
    frame = benchmark_frame(store, benchmark["id"], frame_id)
    with open_benchmark_image(store, frame) as image:
        return prepare_plan_request(image, config["config"]["provider_config"])["image_bytes"]


def run_trial(store, trial_id, progress, cancelled):
    from iris import benchmark_combined_dispatch as dispatch
    from iris import combined_provider as provider
    from iris.benchmark_runs import _context, _persist_result
    from iris.combined_sam import CombinedSam
    from iris.multimodal_provider import ProviderResponseError as ExternalError
    from iris.sam_provider import ProviderResponseError as LocalError
    from iris.sam_provider import normalize_response

    trial = store.get("benchmark_trials", trial_id)
    if trial is None:
        raise KeyError(trial_id)
    benchmark, config, manifest = _context(
        store, trial["benchmark_id"], trial["config_id"], trial["split"]
    )
    frozen = trial["config"]
    frames = [frame for frame in manifest["frames"] if frame["role"] == trial["split"]]
    if (
        frozen.get("protocol") != PROTOCOL
        or frozen.get("source_config_fingerprint") != config["fingerprint"]
        or frozen.get("benchmark_manifest_sha256") != benchmark["manifest_sha256"]
        or frozen.get("candidate_config") != config["config"]
        or frozen.get("role") != trial["split"]
        or frozen.get("work") != work_plan(config["config"], len(frames))
    ):
        raise ValueError("Frozen combined trial inputs changed")
    plan = dispatch.validate_external_trial(frozen, config["config"], frames)
    prepared_plan = prepare_plan(store, config, frames)
    if any(prepared_plan[key] != plan[key] for key in ("requests", "estimate", "runtime_identity")):
        raise BenchmarkConflict("Combined inputs or local runtime changed since approval")
    if prepared_plan["provider_status"]["status"] != "ready":
        raise ValueError(prepared_plan["provider_status"]["reason"])
    result = {
        "trial_id": trial_id,
        "frames_total": len(frames),
        "outputs_created": 0,
        "frames_ready": 0,
        "frames_issues": 0,
        "cancelled": False,
        "quality": None,
        "model_load_ms": None,
    }
    if cancelled():
        return {**result, "cancelled": True}
    attempt = result["benchmark_attempt_id"] = dispatch.claim_trial(store, trial_id)
    _persist_result(store, trial, result)
    settings = config["config"]["provider_config"]
    remote = provider.CombinedOpenAI(settings)
    local = CombinedSam(store.root, settings, plan["runtime_identity"])
    outputs = {row["frame_id"]: row for row in store.list("benchmark_outputs", trial_id=trial_id)}

    def send(output_id, stage, prepared):
        def before_dispatch():
            if cancelled():
                raise BenchmarkConflict("Combined trial stopped before external dispatch")
            dispatch.begin_stage(
                store, output_id, attempt, stage, request=provider.safe_request(prepared)
            )

        def after_response(raw, metadata):
            dispatch.save_stage_response(
                store,
                output_id,
                attempt,
                stage,
                raw,
                {
                    **metadata,
                    "timing": {"elapsed_ms": metadata.get("elapsed_ms")},
                },
            )

        return remote.request(
            prepared, before_dispatch=before_dispatch, after_response=after_response
        )

    try:
        for index, frame in enumerate(frames):
            if cancelled():
                result["cancelled"] = True
                break
            output_id, stage = outputs[frame["frame_id"]]["id"], "planning"
            started = time.perf_counter()
            try:
                with open_benchmark_image(store, frame) as image:
                    progress(
                        index / len(frames), f"Astra plans class searches for image {index + 1}"
                    )
                    prepared = provider.prepare_plan_request(image, settings)
                    response = send(output_id, stage, prepared)
                    planning = provider.normalize_plan(response["raw_response"], settings)
                    dispatch.complete_stage(store, output_id, attempt, stage, planning)
                    if cancelled():
                        raise BenchmarkConflict("Combined trial stopped after planning")
                    stage = "grounding"
                    dispatch.begin_stage(store, output_id, attempt, stage)
                    progress(
                        index / len(frames),
                        f"SAM grounds the planned phrases for image {index + 1}",
                    )
                    local_started = time.perf_counter()
                    raw = local.predict(image, planning, cancelled=cancelled)
                    result["model_load_ms"] = local.model_load_ms
                    metadata = {
                        **local.metadata,
                        "timing": {
                            "elapsed_ms": (time.perf_counter() - local_started) * 1000,
                        },
                    }
                    dispatch.save_stage_response(store, output_id, attempt, stage, raw, metadata)
                    grounded = normalize_response(
                        raw,
                        provider.sam_config_for_plan(settings, planning),
                        width=frame["width"],
                        height=frame["height"],
                    )
                    dispatch.complete_stage(store, output_id, attempt, stage, grounded)
                    if cancelled():
                        raise BenchmarkConflict("Combined trial stopped after local grounding")
                    stage = "review"
                    progress(
                        index / len(frames), f"Astra reviews SAM proposals for image {index + 1}"
                    )
                    prepared = provider.prepare_review_request(image, settings, planning, grounded)
                    response = send(output_id, stage, prepared)
                    normalized = provider.normalize_review(
                        response["raw_response"], settings, grounded
                    )
                    dispatch.complete_stage(store, output_id, attempt, stage, normalized)
                    if cancelled():
                        raise BenchmarkConflict("Combined trial stopped after review")
                    row = dispatch.publish_output(
                        store,
                        output_id,
                        attempt,
                        normalized,
                        {
                            "reference_withheld": True,
                            "frame_sha256": frame["sha256"],
                            "config_fingerprint": config["fingerprint"],
                            "timing": {"elapsed_ms": (time.perf_counter() - started) * 1000},
                        },
                    )
            except (ExternalError, LocalError) as exc:
                row = dispatch.fail_stage(
                    store,
                    output_id,
                    attempt,
                    stage,
                    str(exc),
                    raw=exc.raw_response,
                    metadata=exc.metadata,
                    response_received=getattr(
                        exc,
                        "response_received",
                        stage == "grounding" and exc.raw_response is not None,
                    ),
                )
            except (ValueError, RuntimeError, TypeError, KeyError, OSError) as exc:
                row = dispatch.fail_stage(
                    store, output_id, attempt, stage, str(exc) or type(exc).__name__
                )
            dispatch.record_image_timing(
                store, output_id, attempt, (time.perf_counter() - started) * 1000
            )
            result["outputs_created"] += 1
            result["frames_issues" if row["error"] is not None else "frames_ready"] += 1
            result["cancelled"] = cancelled() or row["metadata"]["state"] == "cancelled"
            _persist_result(store, trial, result)
            progress(
                (index + 1) / len(frames), f"Saved {index + 1} / {len(frames)} combined images"
            )
            if row["error"] is not None or result["cancelled"]:
                break
        result["quality"] = {
            **score_benchmark_outputs(
                manifest, trial["split"], store.list("benchmark_outputs", trial_id=trial_id)
            ),
            "protocol": COMBINED_SCORING,
        }
        _persist_result(store, trial, result)
        return result
    finally:
        local.close()
